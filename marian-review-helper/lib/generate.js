// 프론트에서 온 설문 답변을 프롬프트용 텍스트로 정리
// 비제휴 '예식 지역' 칸에 홀 이름이 섞여 들어와도(예: "인천 송도컨벤시아") 지역으로 보이는 단어만 남긴다.
// 블랙리스트는 새 홀 이름에 뚫리므로 화이트리스트: 시·도 이름, 시/군/구/동/읍/면으로 끝나는 말, 자주 쓰는 지역 별칭.
const PROVINCES = /^(서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)(특별시|광역시|특별자치시|특별자치도|도)?$/;
const REGION_SUFFIX = /^[가-힣]{1,5}(시|군|구|동|읍|면)$/;
const REGION_ALIASES = new Set([
  "수원", "용인", "성남", "분당", "판교", "고양", "일산", "안양", "평촌", "부천", "화성", "동탄", "평택",
  "의정부", "남양주", "하남", "광명", "시흥", "안산", "김포", "파주", "구리", "오산", "이천", "광교", "위례",
  "송도", "청라", "강남", "강북", "강서", "강동", "잠실", "여의도", "홍대", "신촌", "목동", "마곡", "건대",
  "천안", "아산", "청주", "전주", "창원", "김해", "포항", "구미", "원주", "춘천", "강릉", "제주", "서귀포",
]);
function cleanRegion(text) {
  return String(text || "")
    .split(/[\s,/·]+/)
    .filter((w) => w && !/(홀|호텔|웨딩|컨벤|채플|가든|타워|센터|볼룸)/.test(w))
    .filter((w) => PROVINCES.test(w) || REGION_SUFFIX.test(w) || REGION_ALIASES.has(w))
    .slice(0, 3)
    .join(" ");
}

