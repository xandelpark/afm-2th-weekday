// Anthropic Claude(Opus 4.8) 공식 SDK 사용. ANTHROPIC_API_KEY 환경변수 필요.

const Anthropic = require("@anthropic-ai/sdk");
const client = new Anthropic(); // ANTHROPIC_API_KEY 를 환경변수에서 읽음

// Claude 호출
async function callClaude(system, userText) {
  // 모델이 생각(thinking)에 토큰을 다 쓰면 본문이 빈 채로 돌아온다 — 그때는 한 번 더 시도
  for (let attempt = 0; attempt < 2; attempt++) {
    const msg = await client.messages.create({
      model: process.env.ANTHROPIC_MODEL || "claude-opus-4-8",
      max_tokens: 8000, // 블로그 장문(1000자+) + 생각 토큰 여유
      system,
      messages: [{ role: "user", content: userText }],
    });
    const text = (msg.content || [])
      .filter((b) => b.type === "text")
      .map((b) => b.text)
      .join("")
      .trim();
    if (text) return text;
    console.warn("[generate] 빈 응답 — 재시도", msg.stop_reason);
  }
  const e = new Error("후기 생성이 잠시 실패했어요. 다시 한 번 눌러 주세요.");
  e.status = 503;
  throw e;
}

